import 'package:absen_aaj/features/attendance/domain/attendance_models.dart';
import 'package:absen_aaj/features/attendance/domain/attendance_payload.dart';
import 'package:flutter_test/flutter_test.dart';

main() {
  const gps =
      GpsReading(latitude: -5.1477, longitude: 119.4326, accuracyMeters: 25.0);
  final at = DateTime(2026, 10, 6, 8, 30);
  final capturedAt = DateTime(2026, 10, 6, 8, 29, 30);

  group('attendance payload', () {
    test('check-in payload has correct fields', () {
      final fields = buildEventFields(
        clientEventId: 'uuid-A',
        deviceUuid: 'device-1',
        eventType: AttendanceEventType.checkIn,
        eventAt: at,
        gps: gps,
        capturedAt: capturedAt,
      );

      expect(fields['client_event_id'], 'uuid-A');
      expect(fields['device_uuid'], 'device-1');
      expect(fields['event_type'], 'CHECK_IN');
      expect(fields['event_at'], isNotEmpty);
      expect(fields['latitude'], '-5.1477');
      expect(fields['longitude'], '119.4326');
      expect(fields['accuracy_meters'], '25.00');
      expect(fields.containsKey('captured_at'), isTrue);
    });

    test('check-out payload uses CHECK_OUT', () {
      final fields = buildEventFields(
        clientEventId: 'uuid-B',
        deviceUuid: 'device-1',
        eventType: AttendanceEventType.checkOut,
        eventAt: at,
        gps: gps,
        capturedAt: capturedAt,
      );

      expect(fields['event_type'], 'CHECK_OUT');
    });

    test('client never sends authoritative fields', () {
      final fields = buildEventFields(
        clientEventId: 'uuid-C',
        deviceUuid: 'device-1',
        eventType: AttendanceEventType.checkIn,
        eventAt: at,
        gps: gps,
        capturedAt: capturedAt,
      );

      expect(fields.containsKey('distance_meters'), isFalse,
          reason: 'server must compute distance');
      expect(fields.containsKey('location_valid'), isFalse,
          reason: 'server must compute location validity');
      expect(fields.containsKey('status'), isFalse);
      expect(fields.containsKey('employee_id'), isFalse);
      expect(fields.containsKey('branch_id'), isFalse);
    });

    test('different events get different client_event_ids', () {
      // client_event_id is generated by the caller; the builder only carries it.
      final a = buildEventFields(
        clientEventId: 'uuid-X',
        deviceUuid: 'd',
        eventType: AttendanceEventType.checkIn,
        eventAt: at,
        gps: gps,
        capturedAt: capturedAt,
      );
      final b = buildEventFields(
        clientEventId: 'uuid-Y',
        deviceUuid: 'd',
        eventType: AttendanceEventType.checkOut,
        eventAt: at,
        gps: gps,
        capturedAt: capturedAt,
      );

      expect(a['client_event_id'], isNot(equals(b['client_event_id'])));
    });

    test('form data contains the photo multipart file and GPS fields', () {
      final form = buildEventFormData(
        clientEventId: 'uuid-P',
        deviceUuid: 'device-1',
        eventType: AttendanceEventType.checkIn,
        eventAt: at,
        gps: gps,
        capturedAt: capturedAt,
        photoBytes: [1, 2, 3, 4],
      );

      final file = form.files.singleWhere((f) => f.key == 'photo');
      expect(file.value.filename, 'selfie.jpg');
      expect(form.fields.any((f) => f.key == 'latitude'), isTrue);
      expect(form.fields.any((f) => f.key == 'accuracy_meters'), isTrue);
      expect(form.fields.any((f) => f.key == 'distance_meters'), isFalse);
      expect(form.fields.any((f) => f.key == 'location_valid'), isFalse);
    });
  });
}
